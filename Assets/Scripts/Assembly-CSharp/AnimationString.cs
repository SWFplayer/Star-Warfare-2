	public static string GetFlyAniString(MoveDirection dir)
	{
		string result = FlyForward;
		switch (dir)
		{
		case MoveDirection.Forward:
			result = FlyForward;
			break;
		case MoveDirection.Backward:
			result = FlyBack;
			break;
		case MoveDirection.Left:
			result = FlyLeft;
			break;
		case MoveDirection.Right:
			result = FlyRight;
			break;
		}
		return result;
	}

	public static string GetDirectionString(MoveDirection dir)
	{
		string result = DIRECTION_FORWARD;
		switch (dir)
